    [Fact]
    public void AFirstTierStepIsCoveredByEachWayTheCheckListsAndByNothingElse()
    {
        var catalog = ExplainerPlanner.Plan(Scenario());
        bool Covers(object slide, string step) => !ExplainerWriter.Gaps(catalog, Check(catalog, slide)).Contains(new ExplainerGap("step", step));
        const string decision = "decision:src/Clock.cs#0", edge = "edge:root:c→a", cycle = "cycle:root:a→b";

        Assert.True(Covers(S("Targets it", "decision", "decision:src/Clock.cs#0"), decision));
        Assert.True(Covers(S("Targets its file", "hunk", "hunk:src/Clock.cs#0"), decision));
        Assert.True(Covers(S("Cites its file", "level", "level:root", ["src/Clock.cs"]), decision));
        Assert.True(Covers(S("Targets its block", "block", "block:a"), decision));
        Assert.True(Covers(S("Targets a type in its file", "type", "type:A.Timer"), cycle));
        Assert.True(Covers(S("Cites its pair", "block", "block:c", ["C.Other → A.Clock"]), edge));
        Assert.True(Covers(S("Targets it", "edge", "edge:a→b"), cycle));

        Assert.False(Covers(S("Brings out its block", "level", "level:root", blocks: ["a"]), decision));
        Assert.False(Covers(S("Another file", "hunk", "hunk:src/Timer.cs#0"), decision));
        Assert.False(Covers(S("Another edge", "edge", "edge:c→a", ["C.Other → A.Clock"]), cycle));
        Assert.False(Covers(S("The block of an edge's end", "block", "block:a"), edge));
    }

    [Fact]
    public void AChangedBlockIsCoveredByASlideOnAnythingInsideItAndACompleteExplainerReportsNothing()
    {
        var catalog = ExplainerPlanner.Plan(Scenario());
        List<string> Blocks(params object[] slides) => ExplainerWriter.Gaps(catalog, Check(catalog, slides)).Where(g => g.Kind == "block").Select(g => g.Id).ToList();

        Assert.Equal(["a", "b"], Blocks(S("Inside C", "hunk", "hunk:src/Other.cs#0")));
        Assert.Equal(["c", "b"], Blocks(S("A type of A", "type", "type:A.Timer")));
        Assert.Equal(["a"], Blocks(S("Brought out", "level", "level:root", blocks: ["b", "c"])));
        Assert.Equal(["a", "c", "b"], Blocks(S("An edge at the top", "edge", "edge:c→a")));
        Assert.Empty(ExplainerWriter.Gaps(catalog, Check(catalog, Complete)));
    }

    [Fact]
    public async Task RequestsTheRejectedSlidesAndTheUncoveredStepsOnceMoreAndDropsWhatFailsTwice()
    {
        var catalog = ExplainerPlanner.Plan(Scenario());
        var claude = new FakeClaude(
            Answer(
                Complete[0],
                S("Made up", "block", "block:core.foo"),
                S("Wrong file", "edge", "edge:c→a", ["src/Nowhere.cs"]),
                Complete[1], Complete[3], Complete[4]),
            Answer(
                S("Still made up", "block", "block:core.bar", replaces: 2),
                S("Timer closes a cycle", "edge", "edge:a→b", ["A.Timer → B.Caller"], replaces: 0, after: 1)));

        var explainer = await ExplainerWriter.WriteAsync(catalog, Context, claude, null);

        // The rejected slides are gone, with the gaps closed, and the new slide sits after the first.
        Assert.Equal(["Clock learns UTC", "Timer closes a cycle", "Other reads the clock", "Now takes a zone flag", "A is where time lives"], explainer.Slides.Select(s => s.Title));
        Assert.Equal(2, explainer.Dropped);
        Assert.Equal(
        [
            "Slide 'Made up': its target block block:core.bar is not in the catalog",
            "Slide 'Wrong file': it cites src/Nowhere.cs, which is neither a changed file nor a type pair of a changed edge",
        ], explainer.Reasons);
        Assert.Empty(explainer.Uncovered);

        var retry = claude.Requests[1];
        Assert.Equal(Prompts.Read("explainer-retry.schema.json"), retry.Schema);
        Assert.Contains("2. Made up: rejected, because its target block block:core.foo is not in the catalog.", retry.Prompt, StringComparison.Ordinal);
        Assert.Contains("1. Clock learns UTC (target `level:root`): Clock learns UTC.", retry.Prompt, StringComparison.Ordinal);
        Assert.Contains("- the first-tier step: A, B now form a cycle, closed by A → B (`edge:a→b`)", retry.Prompt, StringComparison.Ordinal);
        Assert.Equal(2, claude.Requests.Count);
    }

    [Fact]
    public async Task ReportsWhatStaysUncoveredAndFailsWhenNoSlidePasses()
    {
        var catalog = ExplainerPlanner.Plan(Scenario());
        var partial = await ExplainerWriter.WriteAsync(catalog, Context, new FakeClaude(Answer(Complete[4]), Answer()), null);
        Assert.Equal(
        [
            new ExplainerGap("step", "edge:root:c→a"), new ExplainerGap("step", "cycle:root:a→b"),
            new ExplainerGap("block", "c"), new ExplainerGap("block", "b"),
        ], partial.Uncovered);
        Assert.Equal(0, partial.Dropped);

        await Assert.ThrowsAsync<ClaudeException>(() => ExplainerWriter.WriteAsync(catalog, Context,
            new FakeClaude(Answer(S("Made up", "block", "block:core.foo")), Answer()), null));
    }

    [Fact]
    public async Task KeysTheRequestWithoutAPathReadsTheCacheAndReplacesItOnRegeneration()
    {
        var catalog = ExplainerPlanner.Plan(Scenario());
        var context = Context with { WorkingDirectory = "C:/somewhere/head", Model = "claude-opus-5-5" };
        var cache = new MemoryExplainerCache();
        var claude = new FakeClaude(Answer(Complete), Answer([.. Complete.Reverse()]));

        var first = await ExplainerWriter.WriteAsync(catalog, context, claude, cache);
        var again = await ExplainerWriter.WriteAsync(catalog, context, claude, cache);
        Assert.Same(first, again);
        var request = Assert.Single(claude.Requests);
        Assert.Equal(("C:/somewhere/head", "claude-opus-5-5", NarrativeWriter.Tools), (request.WorkingDirectory, request.Model, request.Tools));
        Assert.DoesNotContain("somewhere", request.Prompt, StringComparison.Ordinal);
        Assert.Contains("- `summary`: The clock learns UTC.", request.Prompt, StringComparison.Ordinal);
        Assert.Contains("Make the clock aware of UTC", request.Prompt, StringComparison.Ordinal);

        var regenerated = await ExplainerWriter.WriteAsync(catalog, context, claude, cache, regenerate: true);
        Assert.Equal("A is where time lives", regenerated.Slides[0].Title);
        Assert.Same(regenerated, Assert.Single(cache.Entries).Value);
        Assert.Equal(2, cache.Writes);
        Assert.NotEqual(ExplainerWriter.RequestKey(ExplainerWriter.Prompt(catalog, context), context),
            ExplainerWriter.RequestKey(ExplainerWriter.Prompt(catalog, context), context with { Model = "sonnet" }));
    }

    [Fact]
    public void TheExplainerDefaultsToOpusAndTheModelOptionReplacesIt()
    {
        Assert.Equal("claude-opus-5-5", ClaudeModels.Default.Explainer);
        Assert.Equal("sonnet", ClaudeModels.All("sonnet").Explainer);
    }

    /// <summary>Compares targets by value, with their lists of blocks compared item by item.</summary>
    private sealed class TargetComparer : IEqualityComparer<ExplainerTarget>
    {
        public bool Equals(ExplainerTarget? x, ExplainerTarget? y) =>
            x is not null && y is not null && x with { Blocks = null } == y with { Blocks = null } && (x.Blocks ?? []).SequenceEqual(y.Blocks ?? []);

        public int GetHashCode(ExplainerTarget obj) => obj.Kind.GetHashCode(StringComparison.Ordinal);
    }
