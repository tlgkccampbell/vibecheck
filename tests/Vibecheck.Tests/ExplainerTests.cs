/// <summary>Stores explainers in memory, and counts the writes.</summary>
internal sealed class MemoryExplainerCache : IExplainerCache
{
    public Dictionary<string, Explainer> Entries { get; } = new(StringComparer.Ordinal);

    public int Writes { get; private set; }

    public Explainer? ReadExplainer(string key) => Entries.GetValueOrDefault(key);

    public void WriteExplainer(string key, Explainer explainer)
    {
        Entries[key] = explainer;
        Writes++;
    }
}

/// <summary>Tests of the explainer's catalog, check, coverage, retry and cache. See <c>docs/explainers.md</c> section 7.</summary>
public class ExplainerTests
{
    private static readonly Lazy<Changeset> Shared = new(Build);

    /// <summary>
    /// Returns the changeset of the scenario, built once: <c>Clock.Now</c> gains a parameter, which Caller follows; Other
    /// starts calling Clock, a new edge from C to A; a new Timer uses Caller, closing a cycle between A and B; three new
    /// policies make "Policy" a new concept; and a generated file changes.
    /// </summary>
    private static Changeset Scenario() => Shared.Value;

    private static Changeset Build()
    {
        const string clock = "namespace A;\n\npublic class Clock\n{\n    public int Now(int zone) => zone;\n}\n";
        const string caller = "namespace B;\n\npublic class Caller\n{\n    public int First(A.Clock clock) => clock.Now(1);\n}\n";
        const string other = "namespace C;\n\npublic class Other\n{\n    public int Value => 1;\n}\n";
        const string gen = "// <auto-generated/>\nnamespace C;\n\npublic class Gen\n{\n    public int Value => 1;\n}\n";
        var before = new Dictionary<string, string> { ["src/Clock.cs"] = clock, ["src/Caller.cs"] = caller, ["src/Other.cs"] = other, ["src/Gen.g.cs"] = gen };
        var after = new Dictionary<string, string>
        {
            ["src/Clock.cs"] = clock.Replace("Now(int zone)", "Now(int zone, bool utc)"),
            ["src/Caller.cs"] = caller.Replace("Now(1)", "Now(1, true)"),
            ["src/Other.cs"] = other.Replace("public int Value => 1;", "public int Value(A.Clock clock) => clock.Now(2, false);"),
            ["src/Gen.g.cs"] = gen.Replace("=> 1", "=> 2"),
            ["src/Timer.cs"] = "namespace A;\n\npublic class Timer\n{\n    public B.Caller Caller { get; set; }\n}\n",
            ["src/RetryPolicy.cs"] = "namespace A;\n\npublic class RetryPolicy\n{\n}\n",
            ["src/CachePolicy.cs"] = "namespace B;\n\npublic class CachePolicy\n{\n}\n",
            ["src/LimitPolicy.cs"] = "namespace C;\n\npublic class LimitPolicy\n{\n}\n",
        };
        var cs = Snippets.Changeset(before, after);
        // A test step and a pattern step, which the scenario's code does not produce, so that every kind has an entry.
        return cs with
        {
            Path =
            [
                .. cs.Path,
                new PathStep("test:Snippets.Tests.ClockTests", "then", "test", "Snippets.Tests.ClockTests", "assertion changed in ClockTests.Now", ["tests/ClockTests.cs"]),
                new PathStep("pattern:policy:A.RetryPolicy", "then", "pattern", "A.RetryPolicy", "RetryPolicy departs from Policy", ["src/RetryPolicy.cs"]) { Pattern = "policy" },
            ],
        };
    }

    private static readonly ExplainerContext Context = new("- abc1234 Make the clock aware of UTC\n", [new Narrative(Narrative.SummaryKey, "The clock learns UTC.", ["a"])]);

    /// <summary>Returns an answer that holds the slides given.</summary>
    private static string Answer(params object[] slides) => JsonSerializer.Serialize(new { slides });

    /// <summary>Returns a slide of an answer.</summary>
    private static object S(string title, string kind, string id, string[]? cites = null, string[]? blocks = null, int? replaces = null, int? after = null) =>
        replaces is null
            ? new { title, text = title + ".", target = new { kind, id, blocks }, cites = cites ?? [] }
            : new { title, text = title + ".", target = new { kind, id, blocks }, cites = cites ?? [], replaces, after = after ?? 0 };

    private static List<ExplainerWriter.SlideCheck> Check(ExplainerCatalog catalog, params object[] slides) =>
        ExplainerWriter.Check(catalog, JsonDocument.Parse(Answer(slides)).RootElement.GetProperty("slides").EnumerateArray());

    /// <summary>The slides that cover the scenario completely: an overview that brings out every block, then one slide per first-tier step.</summary>
    private static readonly object[] Complete =
    [
        S("Clock learns UTC", "level", "level:root", blocks: ["a", "b", "c"]),
        S("Other reads the clock", "edge", "edge:c→a", ["C.Other → A.Clock"]),
        S("Timer closes a cycle", "edge", "edge:a→b", ["A.Timer → B.Caller"]),
        S("Now takes a zone flag", "decision", "decision:src/Clock.cs#0", ["src/Clock.cs"]),
        S("A is where time lives", "block", "block:a"),
    ];

    [Fact]
    public void ListsTheLevelsTheStepsAsTargetsTheHunksTheNewTypesAndConceptsAndACycleAsItsClosingEdge()
    {
        var catalog = ExplainerPlanner.Plan(Scenario());

        var root = Assert.Single(catalog.Levels);
        Assert.Equal(("level:root", new ExplainerTarget("level", "root")), (root.Id, root.Target));
        Assert.Equal(["a", "b", "c"], root.Blocks);
        Assert.Equal(["block:a", "block:c", "block:b"], catalog.Blocks.Select(b => b.Id));

        // Each step of the first two tiers has its target, the cycle's being the edge that closed it.
        Assert.Equal(new Dictionary<string, string>
        {
            ["edge:root:c→a"] = "edge:c→a",
            ["cycle:root:a→b"] = "edge:a→b",
            ["decision:src/Clock.cs#0"] = "decision:src/Clock.cs#0",
            ["node:a"] = "block:a",
            ["test:Snippets.Tests.ClockTests"] = "tests:Snippets.Tests.ClockTests",
            ["pattern:policy:A.RetryPolicy"] = "pattern:policy:A.RetryPolicy",
        }, catalog.StepTargets);
        var closing = catalog.Entries["edge:a→b"];
        Assert.Equal(new ExplainerTarget("edge", "a→b") { Location = "root" }, closing.Target);
        Assert.Equal(["A.Timer → B.Caller"], catalog.StepPairs["cycle:root:a→b"]);
        Assert.Equal("a", catalog.StepBlocks["decision:src/Clock.cs#0"]);

        // The hunks of the files on the path, by index, and none of a generated file, which is not listed at all.
        var clock = Assert.Single(catalog.Files, f => f.Path == "src/Clock.cs");
        Assert.Equal(new ExplainerTarget("hunk", "src/Clock.cs#0") { File = "src/Clock.cs", Index = 0 }, Assert.Single(clock.Hunks).Target);
        Assert.Equal(["src/Other.cs", "src/Timer.cs", "src/Clock.cs", "src/RetryPolicy.cs"], catalog.Files.Select(f => f.Path));
        Assert.DoesNotContain("Gen.g.cs", ExplainerWriter.Prompt(catalog, Context), StringComparison.Ordinal);

        Assert.Equal(["type:A.RetryPolicy", "type:A.Timer"], catalog.Types.Select(t => t.Id));
        var concept = Assert.Single(catalog.Concepts);
        Assert.Equal(("concept:policy", new ExplainerTarget("concept", "term:policy")), (concept.Id, concept.Target));
    }

    [Fact]
    public void ListsAViewWithItsGroupsAndTheEdgesBetweenThem()
    {
        var map = TestData.Map();
        map.Views["by-role"] = new ViewSpec
        {
            Name = "By role", Level = Identifiers.Root,
            Groups = new(StringComparer.Ordinal)
            {
                ["work"] = new GroupSpec { Name = "Work", Leaves = ["a.x", "a.y"] },
                ["serve"] = new GroupSpec { Name = "Serve", Leaves = ["b", "shared"] },
            },
        };

        var catalog = ExplainerPlanner.Plan(NarrativeTests.Context(map).Changeset);

        var view = catalog.Entries["level:view:by-role"];
        Assert.Equal(new ExplainerTarget("level", "view:by-role"), view.Target);
        Assert.Equal(["g:by-role/serve", "g:by-role/work"], view.Blocks);
        Assert.Equal(new ExplainerTarget("edge", "g:by-role/work→g:by-role/serve") { Location = "view:by-role" }, catalog.Entries["edge:g:by-role/work→g:by-role/serve"].Target);
        Assert.Equal(new ExplainerTarget("edge", "a→b") { Location = "root" }, catalog.Entries["edge:a→b"].Target);
    }

    [Fact]
    public void AcceptsASlideOfEachKindResolvedToWhatTheViewerOpens()
    {
        var catalog = ExplainerPlanner.Plan(Scenario());

        var checks = Check(catalog,
            S("Overview", "level", "level:root", blocks: ["block:a", "c"]),
            S("Edge", "edge", "edge:c->a", ["C.Other->A.Clock"]),
            S("Block", "block", "a"),
            S("Decision", "decision", "decision:src/Clock.cs#0", ["src/Clock.cs"]),
            S("Hunk", "hunk", "hunk:src/Timer.cs#0"),
            S("Type", "type", "type:A.Timer"),
            S("Pattern", "pattern", "pattern:policy:A.RetryPolicy"),
            S("Concept", "concept", "concept:policy"),
            S("Tests", "tests", "tests:Snippets.Tests.ClockTests"));

        Assert.All(checks, c => Assert.Null(c.Reason));
        Assert.Equal(
        [
            new ExplainerTarget("level", "root") { Blocks = ["a", "c"] },
            new ExplainerTarget("edge", "c→a") { Location = "root" },
            new ExplainerTarget("block", "a"),
            new ExplainerTarget("decision", "src/Clock.cs#0"),
            new ExplainerTarget("hunk", "src/Timer.cs#0") { File = "src/Timer.cs", Index = 0 },
            new ExplainerTarget("type", "A.Timer"),
            new ExplainerTarget("pattern", "A.RetryPolicy") { Pattern = "policy" },
            new ExplainerTarget("concept", "term:policy"),
            new ExplainerTarget("tests", "Snippets.Tests.ClockTests"),
        ], checks.Select(c => c.Slide!.Target with { Blocks = c.Slide.Target.Blocks?.ToList() }), new TargetComparer());
        Assert.Equal(["C.Other → A.Clock"], checks[1].Slide!.Cites);
    }

    [Fact]
    public void RejectsATargetOutsideTheCatalogABlockNotUnderItsLevelAndAForeignCite()
    {
        var catalog = ExplainerPlanner.Plan(Scenario());

        var checks = Check(catalog,
            S("Unknown", "block", "block:core.foo"),
